def scanned(path: str, text: str, category: Category = Category.UNKNOWN, language: str = "python") -> ScannedFile:
    return ScannedFile(
        Component(path=path, language=language, lines=max(1, len(text.splitlines())),
                  code_lines=max(1, len(text.splitlines())), bytes=len(text.encode()), category=category),
        text,
    )


def test_unknown_is_reachable_and_short_keywords_need_boundaries():
    assert classify(scanned("plain.py", "x = 1\n")).category == Category.UNKNOWN
    result = classify(scanned("src/building.py", "decimal = 'placid'\n"))
    assert result.category not in {Category.USER_SURFACE, Category.PROCESS_MACHINERY}


def test_dot_prefixed_paths_are_preserved():
    cfg = Config(ignore=("gitignore",), overrides={".github": Category.PROCESS_MACHINERY})
    assert not cfg.ignored(".gitignore")
    assert cfg.category_for(".github/workflows/test.yml") == Category.PROCESS_MACHINERY


def test_generated_marker_requires_comment_header_and_python_docstrings_are_not_code():
    assert _looks_generated("# generated by tool\nprint('x')\n")
    assert not _looks_generated("print('this text says generated by a tool')\n")
    text = '\n"""module docs"""\n# comment\nx = 1\n\ndef f():\n    """function docs"""\n    # comment\n    return x\n'
    assert _code_lines(text, "python") == 3


