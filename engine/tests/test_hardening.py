def test_real_import_binding_is_exact_but_bare_cross_file_name_is_probable():
    graph = build_semantic_graph([
        scanned("app.py", "from physics import resolve\ndef run():\n    return resolve()\n", Category.CORE_PRODUCT),
        scanned("physics.py", "def resolve():\n    return 1\n", Category.ESSENTIAL_SUPPORT),
    ], file_dependencies={"app.py": {"physics.py"}, "physics.py": set()})
    call = next(e for e in graph.edges if e.kind == EdgeKind.CALLS and e.target_name == "physics.resolve")
    assert call.resolution == Resolution.EXACT

    graph = build_semantic_graph([
        scanned("app.py", "def run():\n    return helper()\n", Category.CORE_PRODUCT),
        scanned("helper.py", "def helper():\n    return 1\n", Category.ESSENTIAL_SUPPORT),
    ])
    call = next(e for e in graph.edges if e.kind == EdgeKind.CALLS and e.target_name == "helper")
    assert call.resolution == Resolution.PROBABLE


def test_isoupdater_path_resolve_regression_and_mixed_file_roles():
    files = [
        scanned(
            "iso_manager.py",
            "from pathlib import Path\n"
            "class IntegrityStore:\n"
            "    def verify(self, path):\n        return path\n"
            "class LibraryInspector:\n"
            "    def unmatched(self, path):\n        return Path(path).resolve()\n"
            "    def images(self):\n        return []\n",
            Category.VERIFICATION,
        ),
        scanned(
            "iso_updater.py",
            "class ISOScanner:\n"
            "    def resolve_updates(self):\n"
            "        def resolve():\n            return 1\n"
            "        return resolve()\n",
            Category.CORE_PRODUCT,
        ),
    ]
    graph = build_semantic_graph(files)
    bogus = [
        e for e in graph.edges
        if e.kind == EdgeKind.CALLS and e.target_name == "pathlib.Path.resolve"
        and e.resolution == Resolution.EXACT and e.target_id
        and "resolve_updates.resolve" in e.target_id
    ]
    assert bogus == []
    by_name = {s.qualified_name: s for s in graph.symbols.values()}
    assert by_name["IntegrityStore.verify"].category == Category.VERIFICATION
    assert by_name["LibraryInspector.images"].category == Category.ESSENTIAL_SUPPORT


def test_file_dependency_cannot_fabricate_unrelated_exact_import():
    graph = build_semantic_graph([
        scanned("app.py", "import os\ndef run():\n    return os.getcwd()\n", Category.CORE_PRODUCT),
        scanned("physics.py", "def resolve():\n    return 1\n", Category.ESSENTIAL_SUPPORT),
    ], file_dependencies={"app.py": {"physics.py"}, "physics.py": set()})
    edge = next(e for e in graph.edges if e.kind == EdgeKind.IMPORTS)
    assert edge.resolution != Resolution.EXACT
    assert edge.target_id is None or "physics.py" not in edge.target_id


def test_chain_budget_and_zero_product_ratio_are_explicit_json():
    product = Symbol(id="app.py::run@1", path="app.py", language="python", kind=SymbolKind.FUNCTION,
                     name="run", qualified_name="run", start_line=1, end_line=1, category=Category.CORE_PRODUCT)
    symbols = {product.id: product}
    edges = []
    for index in range(20):
        symbol = Symbol(id=f"audit{index}.py::check@1", path=f"audit{index}.py", language="python",
                        kind=SymbolKind.FUNCTION, name=f"check{index}", qualified_name=f"check{index}",
                        start_line=1, end_line=1, category=Category.AUDIT_PROVENANCE)
        symbols[symbol.id] = symbol
        edges.append(SemanticEdge(source_id=symbol.id, kind=EdgeKind.CALLS, target_name="run",
                                  target_id=product.id, resolution=Resolution.EXACT))
    graph = finalize_graph(SemanticGraph(symbols=symbols, edges=edges), max_chain_expansions=3)
    assert graph.chain_truncated and graph.metrics and graph.metrics.chain_expansions == 3

    audit = Symbol(id="audit.py::check@1", path="audit.py", language="python", kind=SymbolKind.FUNCTION,
                   name="check", qualified_name="check", start_line=1, end_line=1,
                   category=Category.AUDIT_PROVENANCE)
    graph = finalize_graph(SemanticGraph(symbols={audit.id: audit}))
    assert graph.metrics and graph.metrics.scaffolding_symbol_ratio is None
    json.dumps(graph.to_dict(), allow_nan=False)


def test_adapter_failure_is_isolated():
    class BrokenAdapter:
        def supports(self, language: str) -> bool: return language == "python"
        def parse(self, item): raise RuntimeError("boom")

    graph = build_semantic_graph([scanned("a.py", "x=1", Category.CORE_PRODUCT)],
                                 registry=AdapterRegistry([BrokenAdapter()]))
    assert graph.metrics is not None
    assert any(d.severity == "error" and "boom" in d.message for d in graph.diagnostics)


